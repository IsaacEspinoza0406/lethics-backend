import { VERIFICATION_MAILER } from '../src/modules/identity/application/verification-mailer';

const uri = process.env.LETHICS_IDENTITY_TEST_URI;
const integration = uri ? describe : describe.skip;

integration('Persistencia de identidad aislada', () => {
  const dbName = `lethics_identity_test_${randomUUID().replace(/-/g, '')}`;
  let connection: Connection;
  let ownsDatabase = false;
  beforeAll(async () => {
    const address = new URL(uri!);
    if (address.protocol !== 'mongodb:' || !['localhost', '127.0.0.1'].includes(address.hostname) || address.port !== '27018') throw new Error('Integration tests require local MongoDB on port 27018');
    connection = await mongoose.createConnection(uri!, { dbName, serverSelectionTimeoutMS: 5000 }).asPromise();
    const databases = await connection.db!.admin().listDatabases();
    if (databases.databases.some((db) => db.name === dbName)) throw new Error('Test database already exists');
    await connection.db!.createCollection('identity_test_marker');
    ownsDatabase = true;
  });
  afterAll(async () => {
    if (connection) {
      if (ownsDatabase && /^lethics_identity_test_[a-f0-9]{32}$/.test(dbName) && connection.name === dbName) await connection.dropDatabase();
      await connection.close();
    }
  });
  it('crea índices y rechaza duplicados, conservando hashes fuera de las consultas y serializaciones', async () => {
    const User = connection.model('Usuario', UsuarioSchema);
    const Token = connection.model('TokenCuenta', TokenCuentaSchema);
    const Session = connection.model('Sesion', SesionSchema);
    await Promise.all([User.createIndexes(), Token.createIndexes()]);
    const userData = { correo: ' TEST@EXAMPLE.INVALID ', contraseñaHash: 'hash-ficticio', nombre: 'Ejemplo', rol: 'rol-ficticio' };
    const user = await User.create(userData);
    await expect(User.create({ ...userData, correo: 'test@example.invalid' })).rejects.toMatchObject({ code: 11000 });
    const tokenData = { usuarioId: user._id, tokenHash: 'token-ficticio', tipo: 'verificacion', creadoEn: new Date(), expiraEn: new Date() };
    const token = await Token.create(tokenData);
    await expect(Token.create(tokenData)).rejects.toMatchObject({ code: 11000 });
    const session = await Session.create({ usuarioId: user._id, refreshTokenHash: 'refresh-ficticio', expiraEn: new Date(), revocadaEn: null });
    expect(await User.findById(user._id).lean()).not.toHaveProperty('contraseñaHash');
    expect(await Token.findById(token._id).lean()).not.toHaveProperty('tokenHash');
    expect(await Session.findById(session._id).lean()).not.toHaveProperty('refreshTokenHash');
    const selected = await User.findById(user._id).select('+contraseñaHash');
    expect(selected?.get('contraseñaHash')).toBe('hash-ficticio');
    expect(selected?.toJSON()).not.toHaveProperty('contraseñaHash');
    expect(await User.findById(user._id).select('+contraseñaHash').lean()).toHaveProperty('contraseñaHash');
    const selectedToken = await Token.findById(token._id).select('+tokenHash');
    const selectedSession = await Session.findById(session._id).select('+refreshTokenHash');
    expect(selectedToken?.toObject()).not.toHaveProperty('tokenHash');
    expect(selectedSession?.toJSON()).not.toHaveProperty('refreshTokenHash');
    const stored = await connection.db!.collection('tokens_cuenta').findOne({ _id: token._id });
    expect(stored?.usuarioId).toBeInstanceOf(mongoose.Types.ObjectId);
    expect(stored?.creadoEn).toBeInstanceOf(Date);
    expect((await User.collection.indexes()).some((index) => index.key.correo === 1 && index.unique)).toBe(true);
    expect((await Token.collection.indexes()).some((index) => index.key.tokenHash === 1 && index.unique)).toBe(true);
  });
  it('registra un estudiante y consume el código una sola vez en transacciones reales', async () => {
    const User = connection.model<Usuario>('Usuario');
    const Token = connection.model<TokenCuenta>('TokenCuenta');
    const mail = new TestVerificationMailer();
    const passwords = new PasswordService();
    const codes = new VerificationCodeService(randomBytes(32), randomBytes(32));
    const registration = new RegistrationService(connection, User, Token, passwords, codes, mail);
    const verify = new VerifyEmailService(connection, User, Token, codes);
    const data = { nombre: 'Persona ficticia', correo: '  NUEVO@EXAMPLE.INVALID ', contraseña: 'contraseña ficticia' };
    await Promise.all([registration.register(data), registration.register(data)]);
    const messages = mail.takeMessages();
    expect(messages).toHaveLength(1);
    const user = await User.findOne({ correo: 'nuevo@example.invalid' }).select('+contraseñaHash');
    expect(user?.get('rol')).toBe('estudiante');
    expect(user?.get('verificadoEn')).toBeNull();
    expect(await passwords.verify(user!.get('contraseñaHash') as string, data.contraseña)).toBe(true);
    const token = await Token.findOne({ usuarioId: user!._id }).select('+tokenHash');
    expect(token!.get('expiraEn').getTime() - token!.get('creadoEn')!.getTime()).toBe(300_000);
    expect(token!.get('tokenHash')).not.toContain(messages[0].code);
    const outcomes = await Promise.all([verify.verify(data.correo, messages[0].code), verify.verify(data.correo, messages[0].code)]);
    expect(outcomes.filter(Boolean)).toHaveLength(1);
    expect(await verify.verify(data.correo, messages[0].code)).toBe(false);
    expect((await User.findById(user!._id))?.get('verificadoEn')).toBeInstanceOf(Date);
  });
  it('rechaza código incorrecto, expirado y revocado sin verificar la cuenta', async () => {
    const User = connection.model<Usuario>('Usuario');
    const Token = connection.model<TokenCuenta>('TokenCuenta');
    const mail = new TestVerificationMailer();
    const codes = new VerificationCodeService(randomBytes(32), randomBytes(32));
    const registration = new RegistrationService(connection, User, Token, new PasswordService(), codes, mail);
    const verify = new VerifyEmailService(connection, User, Token, codes);
    const correo = 'caducado@example.invalid';
    await registration.register({ nombre: 'Ejemplo', correo, contraseña: 'ficticia' });
    const code = mail.takeMessages()[0].code;
    const user = await User.findOne({ correo });
    expect(await verify.verify(correo, code === '000000' ? '000001' : '000000')).toBe(false);
    await Token.updateOne({ usuarioId: user!._id }, { $set: { expiraEn: new Date(0) } });
    expect(await verify.verify(correo, code)).toBe(false);
    await Token.updateOne({ usuarioId: user!._id }, { $set: { expiraEn: new Date(Date.now() + 60_000), revocadoEn: new Date() } });
    expect(await verify.verify(correo, code)).toBe(false);
    expect((await User.findById(user!._id))?.verificadoEn).toBeNull();
  });
  it('revierte la cuenta si falla la creación del token', async () => {
    const User = connection.model<Usuario>('Usuario');
    const Token = connection.model<TokenCuenta>('TokenCuenta');
    const mail = new TestVerificationMailer();
    const codes = new VerificationCodeService(randomBytes(32), randomBytes(32));
    const registration = new RegistrationService(connection, User, Token, new PasswordService(), codes, mail);
    const failure = jest.spyOn(Token, 'create').mockRejectedValueOnce(new Error('fallo simulado') as never);
    try {
      await expect(registration.register({ nombre: 'Ejemplo', correo: 'rollback@example.invalid', contraseña: 'ficticia' })).rejects.toThrow('fallo simulado');
      expect(await User.exists({ correo: 'rollback@example.invalid' })).toBeNull();
      expect(mail.takeMessages()).toHaveLength(0);
    } finally { failure.mockRestore(); }
  });
  it('propaga un fallo de correo sin exponer el código y conserva la transacción confirmada', async () => {
    const User = connection.model<Usuario>('Usuario');
    const Token = connection.model<TokenCuenta>('TokenCuenta');
    const codes = new VerificationCodeService(randomBytes(32), randomBytes(32));
    const service = new RegistrationService(connection, User, Token, new PasswordService(), codes, { sendVerification: async () => { throw new Error('fallo de envío'); } });
    const correo = 'correo-fallido@example.invalid';
    await expect(service.register({ nombre: 'Ejemplo', correo, contraseña: 'ficticia' })).rejects.toThrow('No se pudo procesar el envío');
    const user = await User.findOne({ correo });
    expect(user).not.toBeNull();
    expect(await Token.exists({ usuarioId: user!._id })).not.toBeNull();
  });
  it('bloquea tras cinco fallos y conserva límites al reenviar de forma concurrente', async () => {
    const User = connection.model<Usuario>('Usuario');
    const Token = connection.model<TokenCuenta>('TokenCuenta');
    const mail = new TestVerificationMailer();
    const codes = new VerificationCodeService(randomBytes(32), randomBytes(32));
    const correo = 'limites@example.invalid';
    await new RegistrationService(connection, User, Token, new PasswordService(), codes, mail).register({ nombre: 'Prueba', correo, contraseña: 'ficticia' });
    const oldCode = mail.takeMessages()[0].code;
    const user = await User.findOne({ correo });
    const base = user!.seguridadVerificacion!.ultimaEmision.getTime();
    let now = base + 59_999;
    const policy = { maxFailuresPerHour: 6, maxEmissionsPerHour: 5 };
    const clock = () => new Date(now);
    const verify = new VerifyEmailService(connection, User, Token, codes, policy, clock);
    const resend = new ResendVerificationService(connection, User, Token, codes, mail, policy, clock);
    const wrong = oldCode === '000000' ? '000001' : '000000';
    for (let i = 0; i < 5; i++) expect(await verify.verify(correo, wrong)).toBe(false);
    expect(await verify.verify(correo, oldCode)).toBe(false);
    const token = await Token.findById(user!.seguridadVerificacion!.tokenActualId);
    expect(token?.intentosFallidos).toBe(5);
    await resend.resend(correo);
    expect(mail.takeMessages()).toHaveLength(0);
    now = base + 60_000;
    const generator = jest.spyOn(codes, 'generate').mockReturnValueOnce(oldCode).mockReturnValue('654321' === oldCode ? '654322' : '654321');
    try { await Promise.all([resend.resend(correo), resend.resend(correo)]); } finally { generator.mockRestore(); }
    const messages = mail.takeMessages();
    expect(messages).toHaveLength(1);
    const newCode = messages[0].code;
    expect(newCode).not.toBe(oldCode);
    expect(await verify.verify(correo, oldCode)).toBe(false);
    expect(await verify.verify(correo, newCode)).toBe(false);
    const updated = await User.findOne({ correo });
    expect(updated?.seguridadVerificacion?.fallos).toBe(6);
    expect(updated?.seguridadVerificacion?.emisiones).toBe(2);
  });
  it.each([-1, 0, 1])('aplica el límite de expiración con desplazamiento %i ms', async (offset) => {
    const User = connection.model<Usuario>('Usuario');
    const Token = connection.model<TokenCuenta>('TokenCuenta');
    const mail = new TestVerificationMailer();
    const codes = new VerificationCodeService(randomBytes(32), randomBytes(32));
    const correo = `limite${offset}@example.invalid`;
    await new RegistrationService(connection, User, Token, new PasswordService(), codes, mail).register({ nombre: 'Prueba', correo, contraseña: 'ficticia' });
    const code = mail.takeMessages()[0].code;
    const user = await User.findOne({ correo });
    const expires = user!.seguridadVerificacion!.ultimaEmision.getTime() + 300_000;
    const verify = new VerifyEmailService(connection, User, Token, codes, undefined, () => new Date(expires + offset));
    expect(await verify.verify(correo, code)).toBe(offset < 0);
  });
  it('acumula veinte fallos entre códigos y limita cinco emisiones por hora', async () => {
    const User = connection.model<Usuario>('Usuario');
    const Token = connection.model<TokenCuenta>('TokenCuenta');
    const mail = new TestVerificationMailer();
    const codes = new VerificationCodeService(randomBytes(32), randomBytes(32));
    const correo = 'cuota@example.invalid';
    await new RegistrationService(connection, User, Token, new PasswordService(), codes, mail).register({ nombre: 'Prueba', correo, contraseña: 'ficticia' });
    let code = mail.takeMessages()[0].code;
    const user = await User.findOne({ correo });
    const base = user!.seguridadVerificacion!.ultimaEmision.getTime();
    let now = base;
    const clock = () => new Date(now);
    const verify = new VerifyEmailService(connection, User, Token, codes, undefined, clock);
    const resend = new ResendVerificationService(connection, User, Token, codes, mail, undefined, clock);
    for (let round = 0; round < 4; round++) {
      const wrong = code === '000000' ? '000001' : '000000';
      for (let attempt = 0; attempt < 5; attempt++) await verify.verify(correo, wrong);
      now += 60_001;
      await resend.resend(correo);
      code = mail.takeMessages()[0].code;
    }
    expect((await User.findOne({ correo }))?.seguridadVerificacion?.fallos).toBe(20);
    expect(await verify.verify(correo, code)).toBe(false);
    now += 60_001;
    await resend.resend(correo);
    expect(mail.takeMessages()).toHaveLength(0);
    expect((await User.findOne({ correo }))?.seguridadVerificacion?.emisiones).toBe(5);
  });
  it('serializa verificación y reenvío simultáneos sin dejar dos códigos vigentes', async () => {
    const User = connection.model<Usuario>('Usuario');
    const Token = connection.model<TokenCuenta>('TokenCuenta');
    const mail = new TestVerificationMailer();
    const codes = new VerificationCodeService(randomBytes(32), randomBytes(32));
    const correo = 'carrera@example.invalid';
    await new RegistrationService(connection, User, Token, new PasswordService(), codes, mail).register({ nombre: 'Prueba', correo, contraseña: 'ficticia' });
    const code = mail.takeMessages()[0].code;
    const initial = await User.findOne({ correo });
    const clock = () => new Date(initial!.seguridadVerificacion!.ultimaEmision.getTime() + 60_000);
    const verify = new VerifyEmailService(connection, User, Token, codes, undefined, clock);
    const resend = new ResendVerificationService(connection, User, Token, codes, mail, undefined, clock);
    const [verified] = await Promise.all([verify.verify(correo, code), resend.resend(correo)]);
    const user = await User.findOne({ correo });
    const active = await Token.countDocuments({ usuarioId: user!._id, tipo: 'verificacion', usadoEn: null, revocadoEn: null });
    expect(active).toBeLessThanOrEqual(1);
    expect(Boolean(user!.verificadoEn)).toBe(verified);
    expect(mail.takeMessages().length).toBe(verified ? 0 : 1);
  });
  it('resuelve servicios con Nest y recupera un fallo de correo mediante reenvío interno', async () => {
    const mail = new TestVerificationMailer();
    const jwt = randomBytes(32).toString('base64');
    const hmac = randomBytes(32).toString('base64');
    const limiter = randomBytes(32).toString('base64');
    const module = await Test.createTestingModule({ imports: [ConfigModule.forRoot({ isGlobal: true, ignoreEnvFile: true, load: [() => ({ NODE_ENV: 'test', JWT_ACCESS_SECRET_BASE64: jwt, JWT_ACCESS_ISSUER: 'test', JWT_ACCESS_AUDIENCE: 'test', JWT_ACCESS_TTL_SECONDS: 60, VERIFICATION_CODE_HMAC_KEY_BASE64: hmac, RATE_LIMIT_HMAC_KEY_BASE64: limiter, REDIS_URL: 'redis://:test-only@127.0.0.1:1', VERIFICATION_ACCOUNT_FAILURES_PER_HOUR: 20, VERIFICATION_ACCOUNT_EMISSIONS_PER_HOUR: 5 })] }), MongooseModule.forRoot(uri!, { dbName }), IdentityModule, RateLimitModule] }).overrideProvider(VERIFICATION_MAILER).useValue(mail).compile();
    try {
      const register = module.get(RegistrationService);
      const resend = module.get(ResendVerificationService);
      expect(module.get(VerifyEmailService)).toBeInstanceOf(VerifyEmailService);
      expect(module.get(OriginRateLimitService)).toBeInstanceOf(OriginRateLimitService);
      await expect(module.get(OriginRateLimitService).consume('register', '127.0.0.1', false)).rejects.toThrow('Control de solicitudes no disponible');
      const failure = jest.spyOn(mail, 'sendVerification').mockRejectedValueOnce(new Error('fallo simulado'));
      const correo = 'di-failure@example.invalid';
      await expect(register.register({ nombre: 'Prueba', correo, contraseña: 'ficticia' })).rejects.toThrow('No se pudo procesar el envío');
      failure.mockRestore();
      const User = connection.model<Usuario>('Usuario');
      await User.updateOne({ correo }, { $set: { 'seguridadVerificacion.ultimaEmision': new Date(Date.now() - 60_001) } });
      await resend.resend(correo);
      expect(mail.takeMessages()).toHaveLength(1);
    } finally { await module.close(); }
  });
  it('mantiene fail closed para cuentas anteriores sin estado, sin migrarlas', async () => {
    const User = connection.model<Usuario>('Usuario');
    const Token = connection.model<TokenCuenta>('TokenCuenta');
    const mail = new TestVerificationMailer();
    const codes = new VerificationCodeService(randomBytes(32), randomBytes(32));
    const correo = 'legacy@example.invalid';
    const user = await User.create({ nombre: 'Prueba', correo, contraseñaHash: 'hash-ficticio', rol: 'estudiante', verificadoEn: null });
    await Token.create({ usuarioId: user._id, tipo: 'verificacion', tokenHash: 'legacy-hash-unico', expiraEn: new Date(Date.now() + 300_000) });
    expect(await new VerifyEmailService(connection, User, Token, codes).verify(correo, '123456')).toBe(false);
    await new ResendVerificationService(connection, User, Token, codes, mail).resend(correo);
    expect(mail.takeMessages()).toHaveLength(0);
    expect((await User.findById(user._id))?.seguridadVerificacion).toBeUndefined();
    expect(await Token.countDocuments({ usuarioId: user._id })).toBe(1);
  });
});
