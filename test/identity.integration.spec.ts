import { randomUUID } from 'node:crypto';
import mongoose, { Connection } from 'mongoose';
import { SesionSchema, TokenCuentaSchema, UsuarioSchema, TokenCuenta, Usuario } from '../src/modules/identity/infrastructure/schemas/identity.schemas';
import { randomBytes } from 'node:crypto';
import { PasswordService } from '../src/infrastructure/security/password.service';
import { VerificationCodeService } from '../src/modules/identity/infrastructure/verification-code.service';
import { TestVerificationMailer } from '../src/modules/identity/infrastructure/test-verification-mailer';
import { RegistrationService } from '../src/modules/identity/application/registration.service';
import { VerifyEmailService } from '../src/modules/identity/application/verify-email.service';
import { ResendVerificationService } from '../src/modules/identity/application/resend-verification.service';
import { IdentityModule } from '../src/modules/identity/identity.module';
import { RateLimitModule } from '../src/infrastructure/rate-limit/rate-limit.module';
